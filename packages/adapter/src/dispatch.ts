/**
 * 派活协议：主对话在回复里用标记把任务甩出去，接入层解析后另开无状态会话执行。
 *
 * 实测教训（2026-11-15）：主对话一度把飞书群当成「控制台」，以为要先找东西、
 * 再转发到别处，还要重新找记忆里已有的链接。根因是提示词只写了「怎么处理任务」，
 * 没写「你在哪说话、先查记忆」——规则抢了场景的注意力。所以下方角色说明把
 * 场景与查记忆放在最前面。
 *
 * 为什么用文本标记而不是工具：profile 里解析不到 `@deepseek-ai/dsh-tools`，
 * 插件无法注册工具；标记方案零依赖，且对模型来说和工具一样是「约定的语法」。
 *
 * 格式（宽松解析，容忍全角/多余空白）：
 *   [[SPAWN]] 任务描述 [[/SPAWN]]
 */

/** 派活标记的正则（大小写不敏感，容忍空格）。 */
const SPAWN_PATTERN = /\[\[\s*SPAWN\s*\]\]([\s\S]*?)\[\[\s*\/\s*SPAWN\s*\]\]/gi;

/** 一条解析结果。 */
export interface ParsedReply {
  /** 去掉派活标记后的正文（发给用户的部分）。 */
  readonly text: string;
  /** 要派出去的任务（可能多条）。 */
  readonly tasks: readonly string[];
}

/**
 * 从主对话的回复里抽出派活任务。
 *
 * 标记会被剔除；同一段里多个标记按出现顺序返回。任务为空（只有标记没有内容）时忽略。
 *
 * @param reply - 主对话的完整回复。
 * @returns 清洗后的正文与任务列表。
 */
export function parseSpawn(reply: string): ParsedReply {
  const tasks: string[] = [];
  const text = reply.replace(SPAWN_PATTERN, (_match, body: string) => {
    const task = body.trim();
    if (task.length > 0) tasks.push(task);
    return '';
  });
  return { text: text.replace(/\n{3,}/g, '\n\n').trim(), tasks };
}

/**
 * 回复里是否「声称派了活」。
 *
 * 真实踩过：主对话嘴上说「已经派出执行体去核实」，但没写 `[[SPAWN]]` 标记，
 * 于是什么都没发生。这类空口声称必须能识别出来，否则用户会一直等一个不存在的结果。
 *
 * @param reply - 主对话的完整回复。
 * @returns 是否出现了派活相关措辞。
 */
export function claimsSpawn(reply: string): boolean {
  return /(?:已经?派出|已派|派人去|派了个|派一个|派执行体|派出执行体|派出去核|让人去核实|安排人去)/.test(reply);
}

/**
 * 主对话的角色说明。
 *
 * 首次与某个主对话会话交互时注入一次，之后它就记住了。
 */
export function mainActorBrief(): string {
  return [
    '【场景】你的回复会**直接出现在这个飞书群里**，它就是群消息本身。',
    '不存在「先找到东西、再转发到别处」这一步——当前这段对话就是目的地。',
    '有人请「分享/发一下/告诉我」，直接在群里说出来即可，不要去找接收方。',
    '',
    '【角色】你是这个飞书群的对接主体，所有对话的记忆都在你这里。',
    '',
    '处理方式：',
    '0. **先查现成的**：记忆、档案卡片、工作区文件里常有答案（链接、路径、结论、配置）。',
    '   这些属于「读一下就知道」，**自己查完直接答，不要派活**。',
    '1. 能直接回答的（闲聊、问概念、澄清需求、分享已有信息）——自己答，简洁。',
    '2. **只有这几种才派活**：要跑命令、要操作外部设备/远程主机、要长时间执行/批量处理。',
    '   派法：在回复里写 `[[SPAWN]]完整、自包含的任务描述[[/SPAWN]]`，可以写多条。',
    '   派出去的执行体没有你的对话记忆，任务描述必须把背景、目标、要做什么写全。',
    '3. 派完用一句话告诉用户「已派出」，不要等结果；结果回来会接着给你。',
    '',
    '判断口诀：**读得到的自己查，跑得动的才派出去。**',
    '不要用「我派人去核实了」代替一个你自己查两下就能给出的答案。',
    '',
    '注意：不要声称自己查过东西——没查就是没查；查过就直说依据出处。',
    '同样地，**说「已派出」就必须真的写出 `[[SPAWN]]…[[/SPAWN]]`**。没写标记等于没派，',
    '不要用「已经派人去核实了」这种话糊弄——那会让用户一直等一个不存在的结果。',
  ].join('\n');
}
